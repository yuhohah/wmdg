export type IconName = keyof typeof MAPS;

// Each colour becomes one <path> made of 1px horizontal runs
function toSvgBody(rows: readonly string[]): string {
  const runs: Record<string, string[]> = {};
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (PALETTE[ch]) (runs[ch] ||= []).push(`M${x} ${y}h${end - x}v1h-${end - x}z`);
      x = end;
    }
  });
  return Object.entries(runs).map(([ch, d]) => `<path fill="${PALETTE[ch]}" d="${d.join('')}"/>`).join('');
}

const bodyCache = new Map<IconName, string>();

export function isIconName(value: string): value is IconName {
  return Object.prototype.hasOwnProperty.call(MAPS, value);
}

export function icon(name: IconName, className: string = 'ico'): string {
  let body = bodyCache.get(name);
  if (!body) {
    body = toSvgBody(MAPS[name]);
    bodyCache.set(name, body);
  }
  return `<svg class="${className}" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${body}</svg>`;
}

// Renders a value that may be an icon name; anything else is treated as plain text
export function iconOrText(value: string, className?: string): string {
  return isIconName(value) ? icon(value, className) : value;
}

// Fills every [data-icon] element inside `root` with its icon
export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-icon]').forEach((el) => {
    const name = el.dataset.icon || '';
    if (isIconName(name)) el.innerHTML = icon(name);
  });
}
